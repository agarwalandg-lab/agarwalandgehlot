create table if not exists public.projects (
  slug text primary key,
  content jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.site_content (
  key text primary key,
  content jsonb not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.contact_inquiries (
  id bigint generated by default as identity primary key,
  full_name text not null check (char_length(full_name) between 1 and 120),
  email text not null check (char_length(email) between 3 and 254),
  phone text not null default '' check (char_length(phone) <= 40),
  message text not null check (char_length(message) between 1 and 5000),
  created_at timestamptz not null default now()
);

alter table public.contact_inquiries enable row level security;

drop policy if exists "Anyone can submit contact inquiries" on public.contact_inquiries;
create policy "Anyone can submit contact inquiries"
  on public.contact_inquiries for insert to anon, authenticated
  with check (true);

create table if not exists public.employee_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  employee_code text unique not null,
  full_name text not null,
  email text not null,
  role text not null default 'employee',
  department text not null default 'General',
  phone text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.employee_tasks (
  id bigint generated by default as identity primary key,
  employee_id uuid not null references public.employee_profiles(id) on delete cascade,
  title text not null,
  description text not null default '',
  status text not null default 'pending' check (status in ('pending', 'in_progress', 'done')),
  deadline date,
  created_at timestamptz not null default now()
);

create table if not exists public.employee_attendance (
  id bigint generated by default as identity primary key,
  employee_id uuid not null references public.employee_profiles(id) on delete cascade,
  attendance_date date not null,
  status text not null default 'present' check (status in ('present', 'absent', 'leave', 'half_day')),
  note text not null default '',
  unique (employee_id, attendance_date)
);

create table if not exists public.employee_sales (
  id bigint generated by default as identity primary key,
  employee_id uuid not null references public.employee_profiles(id) on delete cascade,
  report_date date not null,
  total_calls integer not null default 0,
  total_units integer not null default 0,
  site_visits integer not null default 0,
  bookings integer not null default 0,
  remarks text not null default '',
  unique (employee_id, report_date)
);

create table if not exists public.employee_leaves (
  id bigint generated by default as identity primary key,
  employee_id uuid not null references public.employee_profiles(id) on delete cascade,
  start_date date not null,
  end_date date not null,
  reason text not null,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now()
);

create table if not exists public.employee_notices (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  audience text not null default 'all',
  created_at timestamptz not null default now()
);

alter table public.employee_profiles enable row level security;
alter table public.employee_tasks enable row level security;
alter table public.employee_attendance enable row level security;
alter table public.employee_sales enable row level security;
alter table public.employee_leaves enable row level security;
alter table public.employee_notices enable row level security;

