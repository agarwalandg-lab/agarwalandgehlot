create policy "Employees can update own tasks" on public.employee_tasks for update to authenticated using (employee_id = auth.uid()) with check (employee_id = auth.uid());
create policy "Employees can manage own attendance" on public.employee_attendance for all to authenticated using (employee_id = auth.uid()) with check (employee_id = auth.uid());
create policy "Employees can manage own sales" on public.employee_sales for all to authenticated using (employee_id = auth.uid()) with check (employee_id = auth.uid());
create policy "Employees can manage own leaves" on public.employee_leaves for all to authenticated using (employee_id = auth.uid()) with check (employee_id = auth.uid());
create policy "Employees can read notices" on public.employee_notices for select to authenticated using (audience = 'all');

