create table if not exists public.ivory_county_leads (
  id bigint generated by default as identity primary key,
  full_name text not null check (char_length(full_name) between 2 and 120),
  phone text not null check (phone ~ '^[6-9][0-9]{9}$'),
  email text check (char_length(email) between 3 and 254),
  preferred_configuration text,
  budget_expectation text,
  preferred_visit_date date,
  message text,
  project text not null default 'Ivory County Sector 115 Noida',
  modal_type text not null check (modal_type in ('brochure', 'price', 'general')),
  source_section text not null default 'microsite',
  unit_title text,
  utm_params jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.ivory_county_leads disable row level security;

grant select on table public.ivory_county_leads to anon, authenticated;
grant insert on table public.ivory_county_leads to anon, authenticated;
grant usage on sequence public.ivory_county_leads_id_seq to anon, authenticated;
